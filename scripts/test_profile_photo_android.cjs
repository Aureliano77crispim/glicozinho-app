const fs = require('fs');
const html = fs.readFileSync('app/src/main/assets/index.html','utf8');
const kt = fs.readFileSync('app/src/main/java/br/com/glicozinho/app/MainActivity.kt','utf8');
const assert = (x,m)=>{ if(!x) throw new Error(m); };
assert(/id="profileBtn"[^>]*onclick="openScreen\('profile'\)"/.test(html), 'Perfil no cabeçalho não abre a tela de perfil');
assert(/id="profilePhotoInput"[^>]*type="file"[^>]*accept="image\/\*"/.test(html), 'Seletor não aceita imagens');
assert(/onclick="document\.getElementById\('profilePhotoInput'\)\.click\(\)"/.test(html), 'Escolher foto não abre o seletor');
assert(html.includes("file.size>8*1024*1024"), 'Limite de arquivo original ausente');
assert(html.includes("img.naturalWidth*img.naturalHeight>40000000"), 'Limite de dimensões ausente');
assert(html.includes('const max=512'), 'Redimensionamento para 512 px ausente');
assert(html.includes("data.length>450000"), 'Limite de foto comprimida ausente');
assert(/db\.profile\.photo=data/.test(html), 'Foto não é salva no perfil');
assert(/function renderProfilePhoto\(\)/.test(html), 'Renderizador de foto ausente');
assert(/img\.src=photo/.test(html), 'Avatar do cabeçalho não recebe a foto');
assert(/function removeProfilePhoto\(\)/.test(html) && /db\.profile\.photo=''/ .test(html), 'Remoção de foto ausente');
assert(/function applyProfile\(\)[\s\S]*?renderProfilePhoto\(\)/.test(html), 'Foto não é restaurada ao abrir perfil');
assert(kt.includes('override fun onShowFileChooser'), 'WebChromeClient sem seletor de arquivo');
assert(kt.includes('Intent.ACTION_OPEN_DOCUMENT'), 'Seletor Android não usa ACTION_OPEN_DOCUMENT');
assert(kt.includes('fileChooserCallback?.onReceiveValue(result)'), 'URI não retorna ao WebView');
assert(kt.includes('MAX_DATA_BYTES = 2 * 1024 * 1024'), 'Limite de armazenamento ausente');
console.log('PROFILE PHOTO ANDROID TESTS PASSED: perfil, galeria, validação, compressão, persistência, avatar, remoção e integração Android conferidos.');
